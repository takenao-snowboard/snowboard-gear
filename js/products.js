// 既存互換
window.MANUFACTURERS = window.CATALOGS.board;

window.getCatalogByCategory = function getCatalogByCategory(category) {
  return window.CATALOGS[category] || [];
};

window.getAllProducts = function getAllProducts(category) {
  const targets = category
    ? [{ category, manufacturers: window.getCatalogByCategory(category) }]
    : Object.entries(window.CATALOGS).map(([key, makers]) => ({
        category: key,
        manufacturers: makers
      }));

  return targets.flatMap(({ category: cat, manufacturers }) =>
    (manufacturers || []).flatMap(m =>
      (m.products || []).map(p => ({
        category: cat,
        maker: m.maker,
        id: p.id,
        name: p.name,
        season: p.season || "2025-2026"
      }))
    )
  );
};

window.findProductByCategoryAndId = function findProductByCategoryAndId(category, id) {
  const manufacturers = window.getCatalogByCategory(category);

  for (const maker of manufacturers) {
    for (const product of maker.products || []) {
      if (product.id === id) {
        return {
          category,
          maker: maker.maker,
          ...product
        };
      }
    }
  }

  return null;
};
